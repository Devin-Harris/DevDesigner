/**
 * Regenerates the app-schema baseline migration from the current entities:
 *   npx ts-node --transpile-only scripts/generate-baseline.ts
 * Only for squashing. After a baseline ships, schema changes get their own migration
 * in src/platform/database/migrations (the migrations spec fails until they do).
 */
import 'reflect-metadata';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { DataSource } from 'typeorm';

const NAME = 'Baseline1795000000000';
const OUT = join(__dirname, '../src/platform/database/migrations/1795000000000-Baseline.ts');

async function main(): Promise<void> {
  const ds = new DataSource({
    type: 'better-sqlite3',
    database: ':memory:',
    entities: [join(__dirname, '../src/**/*.entity.ts')],
  });
  await ds.initialize();
  const sql = await ds.driver.createSchemaBuilder().log();
  await ds.destroy();
  const up = sql.upQueries
    .map((q) => `    await queryRunner.query(${JSON.stringify(q.query)});`)
    .join('\n');
  const tables = sql.upQueries
    .map((q) => /^CREATE TABLE "([^"]+)"/.exec(q.query)?.[1])
    .filter((t): t is string => !!t && !t.startsWith('temporary_'));
  const down = [...new Set(tables)]
    .reverse()
    .map((t) => `    await queryRunner.query(${JSON.stringify(`DROP TABLE IF EXISTS "${t}"`)});`)
    .join('\n');
  writeFileSync(
    OUT,
    `import { MigrationInterface, QueryRunner } from 'typeorm';

/**
 * Full app schema as of the desktop baseline (generated by scripts/generate-baseline.ts).
 * Databases that run migrations (desktop / DATABASE_MIGRATIONS_RUN) start here; the
 * older root \`server/migrations\` were incremental patches on synchronize-created DBs.
 */
export class ${NAME} implements MigrationInterface {
  name = '${NAME}';

  public async up(queryRunner: QueryRunner): Promise<void> {
${up}
  }

  public async down(queryRunner: QueryRunner): Promise<void> {
${down}
  }
}
`,
  );
  console.log(`wrote ${OUT} (${sql.upQueries.length} statements)`);
}
void main();
