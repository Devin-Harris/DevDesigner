/**
 * Writes a migration for whatever the entities need beyond the existing migrations:
 *   npx ts-node --transpile-only scripts/generate-migration.ts AddSomething
 * (Runs every migration in src/platform/database/migrations on an empty in-memory
 * database, then asks TypeORM what synchronize would still change.)
 */
import 'reflect-metadata';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { DataSource } from 'typeorm';

async function main(): Promise<void> {
  const label = process.argv[2];
  if (!label || !/^[A-Z][A-Za-z0-9]+$/.test(label)) {
    console.error('Usage: generate-migration.ts PascalCaseName');
    process.exit(1);
  }
  const dir = join(__dirname, '../src/platform/database/migrations');
  const ds = new DataSource({
    type: 'better-sqlite3',
    database: ':memory:',
    entities: [join(__dirname, '../src/**/*.entity{.ts,.js}')],
    migrations: [join(dir, '*.ts')],
    migrationsRun: true,
  });
  await ds.initialize();
  const sql = await ds.driver.createSchemaBuilder().log();
  await ds.destroy();
  if (!sql.upQueries.length) {
    console.log('Entities and migrations already match: nothing to generate.');
    return;
  }
  const stamp = Date.now();
  const name = `${label}${stamp}`;
  const q = (list: { query: string }[]) =>
    list.map((x) => `    await queryRunner.query(${JSON.stringify(x.query)});`).join('\n');
  const file = join(dir, `${stamp}-${label}.ts`);
  writeFileSync(
    file,
    `import { MigrationInterface, QueryRunner } from 'typeorm';

/** Generated by scripts/generate-migration.ts. */
export class ${name} implements MigrationInterface {
  name = '${name}';

  public async up(queryRunner: QueryRunner): Promise<void> {
${q(sql.upQueries)}
  }

  public async down(queryRunner: QueryRunner): Promise<void> {
${q([...sql.downQueries].reverse())}
  }
}
`,
  );
  console.log(`wrote ${file} (${sql.upQueries.length} statements)`);
}
void main();
