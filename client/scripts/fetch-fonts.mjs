// Downloads the app's Google Fonts (latin subset, woff2) into src/assets/fonts and
// writes src/assets/fonts/fonts.css, so the app needs no third-party font host and
// works offline (desktop app). Re-run after changing FAMILIES:
//   node scripts/fetch-fonts.mjs
// The CSS keeps Google's "/* latin */" block comments: the SVG export's font
// embedding (features/editor/helpers/font-embed.helper.ts) parses them.
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const FAMILIES = [
   // UI type system (styles.scss).
   'Space+Grotesk:wght@500;600;700',
   'IBM+Plex+Sans:wght@400;500;600',
   'IBM+Plex+Mono:wght@400;500;600',
   // Canvas text-element families (sans, serif, display, condensed, hand-drawn, code).
   'Kalam:wght@400;700',
   'Caveat:wght@400;700',
   'Permanent+Marker',
   'Nunito:ital,wght@0,400;0,600;0,700;1,400;1,600;1,700',
   'Inter:ital,wght@0,400;0,600;0,700;1,400;1,700',
   'Poppins:ital,wght@0,400;0,600;0,700;1,400;1,700',
   'Lora:ital,wght@0,400;0,600;0,700;1,400;1,700',
   'Playfair+Display:ital,wght@0,400;0,600;0,700;1,400;1,700',
   'Oswald:wght@400;600;700',
   'JetBrains+Mono:ital,wght@0,400;0,600;0,700;1,400',
];
// A current browser UA makes Google serve woff2.
const UA =
   'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/140.0 Safari/537.36';

const outDir = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'assets', 'fonts');
rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

const url = `https://fonts.googleapis.com/css2?${FAMILIES.map((f) => `family=${f}`).join('&')}&display=swap`;
const css = await (await fetch(url, { headers: { 'User-Agent': UA } })).text();
const blocks = [...css.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*(@font-face\s*\{[^}]*\})/g)].filter((b) => b[1] === 'latin');
if (!blocks.length) throw new Error('No latin @font-face blocks in the Google response');

const out = [];
for (const [, subset, rule] of blocks) {
   const family = /font-family:\s*['"]?([^;'"]+)['"]?/.exec(rule)[1].trim();
   const style = /font-style:\s*(\w+)/.exec(rule)?.[1] ?? 'normal';
   const weight = /font-weight:\s*(\d+)/.exec(rule)?.[1] ?? '400';
   const src = /url\(([^)]+)\)/.exec(rule)[1].replace(/['"]/g, '');
   const file = `${family.toLowerCase().replace(/\s+/g, '-')}-${weight}${style === 'italic' ? '-italic' : ''}.woff2`;
   writeFileSync(join(outDir, file), Buffer.from(await (await fetch(src)).arrayBuffer()));
   out.push(`/* ${subset} */\n${rule.replace(/url\([^)]+\)/, `url(${file})`)}`);
}
writeFileSync(
   join(outDir, 'fonts.css'),
   `/* Generated by scripts/fetch-fonts.mjs from Google Fonts (SIL Open Font License). */\n${out.join('\n')}\n`
);
console.log(`Wrote ${out.length} font faces to ${outDir}`);
