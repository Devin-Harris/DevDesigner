// Generates src/environments/environment.ts from environment variables at build
// time (Angular inlines config into the bundle; it cannot read env vars at runtime).
// Set API_URL to the server's public origin, e.g. https://devdesigner-api.up.railway.app
// (no trailing /api). With API_URL unset this does nothing, so local builds keep
// using the checked-in localhost defaults. Optional: SENTRY_DSN (browser DSN) and
// TELEMETRY=true (first-party usage beacon, see core/telemetry/telemetry.service.ts).
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const raw = process.env.API_URL?.trim();
if (raw) {
  // `same-origin`: the server hosts this build (self-hosted image), so URLs are relative.
  const origin = raw === 'same-origin' ? '' : raw.replace(/\/+$/, '').replace(/\/api$/, '');
  const target = fileURLToPath(new URL('../src/environments/environment.ts', import.meta.url));
  writeFileSync(
    target,
    `// Generated by scripts/set-env.mjs from API_URL. Do not commit.
export const environment = {
  production: true,
  apiBaseUrl: '${origin}/api',
  wsBaseUrl: '${origin}',
  mcpUrl: '${process.env.mcpUrl?.trim() ?? ''}',
  sentryDsn: '${process.env.SENTRY_DSN?.trim() ?? ''}',
  telemetry: ${process.env.TELEMETRY?.trim() === 'true'},
};
`,
  );
  console.log(`environment.ts generated for API ${origin || '(same origin)'}`);
}
